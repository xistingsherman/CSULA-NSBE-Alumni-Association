// Resume file storage: a private Google Cloud Storage bucket, or a local folder for testing.
// Files are never public. Downloads go through the app, which checks who's asking first,
// then hands out a link that expires after a few minutes (GCS) or sends the file itself (local).
const fs = require('fs/promises');
const path = require('path');
const crypto = require('crypto');
const config = require('./config');

const DOWNLOAD_LINK_MINUTES = 5;

const newObjectName = (memberId) => `resumes/${memberId}/${crypto.randomBytes(12).toString('hex')}.pdf`;

// "My Résumé (final).pdf" -> "My Resume (final).pdf"; safe to put in a download header.
function safeFileName(name) {
  const base = String(name || 'resume')
    .normalize('NFKD').replace(/[̀-ͯ]/g, '')
    .replace(/[^\w .()-]/g, '').replace(/\s+/g, ' ').trim()
    .replace(/\.pdf$/i, '').slice(0, 100) || 'resume';
  return `${base}.pdf`;
}

const disposition = (downloadName) => `attachment; filename="${safeFileName(downloadName)}"`;

function gcsStorage() {
  // Loaded only when a bucket is configured (needs Node 18+).
  const { Storage } = require('@google-cloud/storage');
  const bucket = new Storage().bucket(config.gcsBucket);
  return {
    async save(objectName, buffer, downloadName) {
      await bucket.file(objectName).save(buffer, {
        resumable: false,
        contentType: 'application/pdf',
        metadata: { contentDisposition: disposition(downloadName), cacheControl: 'private, no-store' },
      });
    },
    async remove(objectName) {
      await bucket.file(objectName).delete({ ignoreNotFound: true });
    },
    async send(res, objectName, downloadName) {
      const [url] = await bucket.file(objectName).getSignedUrl({
        version: 'v4',
        action: 'read',
        expires: Date.now() + DOWNLOAD_LINK_MINUTES * 60 * 1000,
        responseDisposition: disposition(downloadName),
        responseType: 'application/pdf',
      });
      res.set('Cache-Control', 'no-store').redirect(303, url);
    },
  };
}

function localStorage() {
  const root = path.join(__dirname, '..', 'uploads');
  // Object names are generated by newObjectName, but never let one escape the uploads folder.
  const fileFor = (objectName) => {
    const file = path.resolve(root, objectName);
    if (!file.startsWith(root + path.sep)) throw new Error('Bad file path');
    return file;
  };
  console.log('Resumes are stored in ./uploads (set GCS_BUCKET to use a GCP bucket).');
  return {
    async save(objectName, buffer) {
      const file = fileFor(objectName);
      await fs.mkdir(path.dirname(file), { recursive: true });
      await fs.writeFile(file, buffer);
    },
    async remove(objectName) {
      await fs.rm(fileFor(objectName), { force: true });
    },
    async send(res, objectName, downloadName) {
      res.set({ 'Content-Disposition': disposition(downloadName), 'Cache-Control': 'private, no-store' });
      res.type('application/pdf').sendFile(fileFor(objectName));
    },
  };
}

const storage = config.gcsBucket ? gcsStorage() : localStorage();

module.exports = { ...storage, newObjectName, safeFileName };
