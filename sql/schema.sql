-- Cal State LA NSBE Alumni Association: Oracle schema
-- Run once in Oracle Cloud > Autonomous Database > Database Actions > SQL.
-- If you're signed in as ADMIN, first run create-user.sql, then this line so the
-- tables are created in the app's schema:
--   ALTER SESSION SET CURRENT_SCHEMA = nsbe_app;

CREATE TABLE members (
  id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  email          VARCHAR2(254) NOT NULL,
  password_hash  VARCHAR2(200),
  member_status  VARCHAR2(10)  DEFAULT 'pending' NOT NULL
                 CONSTRAINT members_status_ck CHECK (member_status IN ('pending', 'approved', 'rejected')),
  member_role    VARCHAR2(10)  DEFAULT 'member' NOT NULL
                 CONSTRAINT members_role_ck CHECK (member_role IN ('member', 'admin')),
  first_name     VARCHAR2(60)  NOT NULL,
  last_name      VARCHAR2(60)  NOT NULL,
  grad_year      NUMBER(4),
  major          VARCHAR2(80),
  job_title      VARCHAR2(100),
  company        VARCHAR2(100),
  industry       VARCHAR2(60),
  city           VARCHAR2(80),
  open_to        VARCHAR2(200),           -- comma-separated: Mentoring,Referrals,Coffee chats
  linkedin_url   VARCHAR2(200),
  bio            VARCHAR2(1500 CHAR),
  resume_object  VARCHAR2(300),            -- file path inside the GCP bucket
  resume_name    VARCHAR2(200),            -- original file name, used for downloads
  resume_uploaded_at TIMESTAMP,
  share_resume   NUMBER(1) DEFAULT 1 NOT NULL,   -- 1 = other members can download their resume
  share_email    NUMBER(1) DEFAULT 0 NOT NULL,   -- 1 = other members can see their email
  listed         NUMBER(1) DEFAULT 1 NOT NULL,   -- 1 = appears in the directory
  is_temp        NUMBER(1) DEFAULT 0 NOT NULL,   -- 1 = temporary admin from TEMP_ADMIN_* settings
  created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT members_email_uq UNIQUE (email)
);

CREATE TABLE sessions (
  token_hash  VARCHAR2(64) PRIMARY KEY,   -- SHA-256 of the cookie token; the token itself is never stored
  member_id   NUMBER NOT NULL REFERENCES members (id) ON DELETE CASCADE,
  expires_at  TIMESTAMP NOT NULL
);

CREATE INDEX sessions_member_ix ON sessions (member_id);

CREATE TABLE join_requests (
  id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  first_name  VARCHAR2(60)  NOT NULL,
  last_name   VARCHAR2(60)  NOT NULL,
  email       VARCHAR2(254) NOT NULL,
  grad_year   NUMBER(4),
  major       VARCHAR2(80),
  interest    VARCHAR2(80),
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
